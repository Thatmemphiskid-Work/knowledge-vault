"""Browser contract tests and review screenshots. Uses a fresh, disposable browser context."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

ROOT = Path(__file__).resolve().parents[1]
ARTIFACTS = ROOT / '.amp/in/artifacts'

def main():
    ARTIFACTS.mkdir(parents=True, exist_ok=True)
    with sync_playwright() as p:
        browser = p.chromium.launch(channel='msedge', headless=True)
        context = browser.new_context(viewport={'width':1440,'height':1000}, accept_downloads=True)
        page = context.new_page()
        errors = []
        page.on('pageerror', lambda e: errors.append(str(e)))
        page.goto('http://127.0.0.1:8765')
        expect(page.locator('#count')).to_have_text('1,739 entries')
        expect(page.locator('#detail > h2')).to_contain_text('BIND')
        page.screenshot(path=str(ARTIFACTS / '01-catalog.png'))
        page.locator('#next').click()
        expect(page.locator('#page')).to_have_text('Page 2 / 145')
        page.locator('#search').fill('CVE-2015-5477')
        expect(page.locator('#count')).to_have_text('1 entries')
        page.locator('#rows button').click()
        page.locator('summary').filter(has_text='Verify applicability').click()
        page.locator('summary').filter(has_text='Validate intrusion').click()
        expect(page.locator('#detail')).to_contain_text('ground-truth start time')
        guide = context.request.get('http://127.0.0.1:8765/guides/detection')
        assert guide.status == 200 and 'Scenario matrix' in guide.text()
        page.locator('#detail').screenshot(path=str(ARTIFACTS / '02-workflow.png'))

        # Observable branch boundaries: absence requires evidence; test failure is inconclusive.
        form = page.locator('#assessment-form')
        form.locator('[name=asset]').fill('example-lab-dns-01')
        form.locator('[name=present]').select_option('no')
        expect(page.locator('#verdict')).to_have_text('Needs inventory evidence')
        form.locator('[name=present]').select_option('yes')
        form.locator('[name=affected]').select_option('yes')
        form.locator('[name=test]').select_option('yes')
        expect(page.locator('#verdict')).to_have_text('Needs applicability evidence')
        form.locator('[name=version]').fill('EXAMPLE BUILD — not a real finding')
        form.locator('[name=advisory]').fill('Example procedure only')
        form.locator('[name=evidence]').fill('EXAMPLE: disposable UI-test record, not an assessment. Vantage point and IDS alert evidence would be recorded here.')
        expect(page.locator('#verdict')).to_have_text('Verified in lab (analyst-recorded)')
        form.locator('[name=test]').select_option('no')
        expect(page.locator('#verdict')).to_have_text('Inconclusive — failed test does not establish absence')
        form.locator('[name=fixed]').select_option('yes')
        expect(page.locator('#verdict')).to_have_text('Fix applied — retest pending')
        form.locator('[name=retest]').select_option('no')
        expect(page.locator('#verdict')).to_have_text('Fix applied — retest failed; investigate')
        form.locator('[name=retest]').select_option('yes')
        expect(page.locator('#verdict')).to_have_text('Remediated — retest recorded')
        form.get_by_role('button', name='Save assessment').click()
        expect(page.locator('#notice')).to_contain_text('Saved CVE-2015-5477')
        page.locator('[data-tab=workbench]').click()
        expect(page.locator('.record')).to_have_count(1)
        page.screenshot(path=str(ARTIFACTS / '03-evidence.png'))
        with page.expect_download() as dl:
            page.locator('#export-json').click()
        backup = json.loads(Path(dl.value.path()).read_text(encoding='utf-8'))
        assert backup['records'][0]['asset'] == 'example-lab-dns-01'
        assert backup['records'][0]['status'] == 'Remediated — retest recorded'
        with page.expect_download() as dl:
            page.locator('#export-md').click()
        assert '[[CVE-2015-5477]]' in Path(dl.value.path()).read_text(encoding='utf-8')
        page.reload()
        expect(page.locator('#count')).to_have_text('1,739 entries')
        page.locator('[data-tab=workbench]').click()
        expect(page.locator('.record')).to_have_count(1)
        # Imported status must be recalculated, not trusted; duplicate import must not duplicate records.
        backup['records'][0]['status'] = 'Forged automatic result'
        backup['records'][0]['retest'] = 'no'
        payload = {'name':'test.json','mimeType':'application/json','buffer':json.dumps(backup).encode()}
        page.locator('#import').set_input_files(payload)
        expect(page.locator('.record')).to_contain_text('retest failed; investigate')
        expect(page.locator('.record')).to_have_count(1)
        page.locator('#import').set_input_files({'name':'bad.json','mimeType':'application/json','buffer':b'{"schema":1,"records":[{}]}'})
        expect(page.locator('#notice')).to_contain_text('Import failed')
        expect(page.locator('.record')).to_have_count(1)
        page.locator('[data-edit]').click()
        expect(form.locator('[name=asset]')).to_have_value('example-lab-dns-01')

        page.locator('[data-tab=library]').click()
        expect(page.locator('.source-card')).to_have_count(11)
        page.locator('#doc-query').fill('patch management')
        page.locator('#doc-form button').click()
        expect(page.locator('.hit').first).to_be_visible()
        assert '#page=' in page.locator('.hit a').first.get_attribute('href')
        page.screenshot(path=str(ARTIFACTS / '04-library.png'))
        page.locator('#doc-query').fill('zzzz-no-such-term-123456789')
        page.locator('#doc-form button').click()
        expect(page.locator('#doc-results')).to_contain_text('0 matching pages')
        assert context.request.get('http://127.0.0.1:8765/data/pages.json').status == 404
        assert context.request.get('http://127.0.0.1:8765/../known_exploited_vulnerabilities.csv').status == 404
        page.locator('[data-tab=guides]').click()
        expect(page.locator('.method-card')).to_have_count(11)
        page.locator('#guide-search').fill('database and process')
        expect(page.locator('.method-card')).to_have_count(1)
        page.locator('.method-card > summary').click()
        expect(page.locator('#guide-list')).to_contain_text('parameter binding')
        expect(page.locator('#guide-list')).to_contain_text('Decision branches')
        page.evaluate('window.scrollTo(0,0)')
        page.screenshot(path=str(ARTIFACTS / '06-methods.png'))
        page.locator('.method-card').screenshot(path=str(ARTIFACTS / '07-method-expanded.png'))
        page.locator('[data-tab=catalog]').click()
        page.locator('#search').fill('CVE-2016-3081')
        page.locator('#rows button').click()
        page.locator('#detail > details > summary').filter(has_text='GitHub defensive').click()
        expect(page.locator('#detail a[href="https://github.com/apache/struts/blob/STRUTS_2_3_28_1/core/src/main/resources/org/apache/struts2/default.properties"]')).to_be_visible()
        page.locator('#detail').screenshot(path=str(ARTIFACTS / '08-code-links.png'))
        page.locator('#search').fill('zzzz-no-such-cve')
        expect(page.locator('#rows')).to_contain_text('No matches')
        page.locator('#search').fill('')
        page.locator('#family').select_option('Windows')
        expect(page.locator('#count')).to_have_text('391 entries')
        page.locator('#family').select_option('')
        page.locator('[data-tab=training]').click()
        expect(page.locator('#training-count')).to_have_text('14 groups · 198 topic entries · 6 hands-on labs')
        expect(page.locator('.training-group-card')).to_have_count(14)
        expect(page.locator('.training-topic')).to_have_count(198)
        expect(page.locator('.training-lab')).to_have_count(6)
        page.evaluate('window.scrollTo(0,0)')
        page.screenshot(path=str(ARTIFACTS / '09-training.png'))
        page.locator('#training-group').select_option('defense-evasion')
        expect(page.locator('.training-topic')).to_have_count(34)
        page.locator('#training-search').fill('Clear Windows Event Logs')
        expect(page.locator('.training-topic')).to_have_count(1)
        page.locator('.training-group-card > summary').click()
        page.locator('.training-topic > summary').click()
        expect(page.locator('.training-topic')).to_contain_text('do not clear logs')
        page.locator('.training-group-card').screenshot(path=str(ARTIFACTS / '10-training-topic.png'))
        page.locator('#lab-pipeline-fixtures > summary').click()
        expect(page.locator('#lab-pipeline-fixtures')).to_contain_text('ConvertFrom-Json')
        expect(page.locator('#lab-pipeline-fixtures')).to_contain_text('not live sensor capture')
        page.locator('#lab-pipeline-fixtures').screenshot(path=str(ARTIFACTS / '11-training-lab.png'))
        page.locator('#training-search').fill('no-such-training-topic-xyz')
        expect(page.locator('#training-results')).to_have_text('0 matching topic entries in 0 groups')
        expect(page.locator('#training-list')).to_contain_text('No matching topics')
        page.locator('#training-search').fill('')
        page.locator('#training-group').select_option('execution')
        page.set_viewport_size({'width':390,'height':844})
        page.evaluate('window.scrollTo(0,0)')
        assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
        page.screenshot(path=str(ARTIFACTS / '12-training-mobile.png'), full_page=True)
        page.locator('#lab-benign-execution > summary').click()
        assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
        page.locator('#lab-benign-execution').screenshot(path=str(ARTIFACTS / '13-training-mobile-lab.png'))
        page.locator('[data-tab=catalog]').click()
        page.evaluate('window.scrollTo(0,0)')
        page.screenshot(path=str(ARTIFACTS / '05-mobile.png'))
        assert not errors, errors
        browser.close()
    print('UI checks passed: catalog/filter/page, evidence branches, persistence/edit, export/import, document search, route restriction and mobile overflow.')

if __name__ == '__main__':
    main()
